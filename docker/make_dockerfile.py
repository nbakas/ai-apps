
###########################################################################
CHROMIUM = True
LATEX_SUPPORT = True # For compiling .tex files into pdf inside python applications
PROD = True
STREAMLIT_SCRIPT = "app.py"
###########################################################################
text = "# GENERATED by make_dockerfile.py - If you edit this Dockerfile do any appropriate changes in the generic make_dockerfile.py as well\n"
flag_entries = []
if CHROMIUM: flag_entries.append("CHROMIUM=True")
if LATEX_SUPPORT: flag_entries.append("LATEX_SUPPORT=True")
if PROD: flag_entries.append("PROD=True")
if PROD and STREAMLIT_SCRIPT: flag_entries.append(f"STREAMLIT_SCRIPT={STREAMLIT_SCRIPT}")
if flag_entries:
    text += "# Flags: %s\n\n" % " ".join(flag_entries)
###########################################################################
text += """
# Base image
FROM python:3.12-slim

# Install basic system dependencies
RUN apt-get update \\
    && apt-get upgrade -y \\
    && apt-get install -y --no-install-recommends \\
    libgomp1 \\
    && rm -rf /var/lib/apt/lists/*
"""
###########################################################################
if CHROMIUM:
    text += """
# Install chromium for Kaleido
RUN apt-get update \\
    && apt-get upgrade -y \\
    && apt-get install -y --no-install-recommends chromium \\
    && rm -rf /var/lib/apt/lists/*
"""
###########################################################################
if LATEX_SUPPORT:
    text += """
# Install LaTeX support
RUN apt-get update \\
    && apt-get upgrade -y \\
    && apt-get install -y --no-install-recommends \\
        texlive-latex-recommended \\
        texlive-latex-extra \\
        texlive-fonts-recommended \\
        texlive-publishers \\
        latexmk \\
    && rm -rf /var/lib/apt/lists/*
"""
###########################################################################
text += """
# Set the working directory
WORKDIR /app
"""
###########################################################################
text += """
# Create the Python virtual environment
ENV VENV=/opt/venv
RUN python3 -m venv "$VENV"
ENV PATH="$VENV/bin:$PATH"

# Install `uv` and `pip-audit`
RUN pip install --no-cache-dir --only-binary=:all: uv pip-audit

# Copy requirements file
COPY requirements.txt .

# Fail the build on known vulnerabilities
RUN pip-audit -r requirements.txt --require-hashes --disable-pip

# Install locked Python packages
RUN uv pip sync requirements.txt \\
    --require-hashes \\
    --only-binary=:all:

# Check Python package compatibility
RUN uv pip check
"""
###########################################################################
text += """
# Create a non-root user
RUN useradd -m -u 1000 appuser \\
    && mkdir -p /home/appuser/.cache/huggingface \\
    && chown -R appuser:appuser /home/appuser

## Configure environment variables for the non-root user
ENV HOME=/home/appuser \\
    XDG_CACHE_HOME=/home/appuser/.cache \\
    HF_HOME=/home/appuser/.cache/huggingface
"""
###########################################################################
if PROD:
    text += """
# Copy the application code into the container (production only)
# Do not forget the dockerignore file
COPY app.py *.so ./
"""
###########################################################################
text += """
# Run as the non-root user
USER appuser
"""
###########################################################################
if PROD:
    text += f"""
# Declare the Streamlit port
EXPOSE 8501

## Start the Streamlit application
CMD ["python", \\
    "-m", \\
    "streamlit", \\
    "run", \\
    "{STREAMLIT_SCRIPT}", \\
    "--server.address=0.0.0.0", \\
    "--server.port=8501", \\
    "--server.fileWatcherType=none", \\
    "--browser.gatherUsageStats=false", \\
    "--browser.serverAddress=localhost", \\
    "--server.headless=true"]
"""
###########################################################################
with open("Dockerfile", "w", encoding="utf-8", newline="\n") as out_file: 
    out_file.write(text)
###########################################################################